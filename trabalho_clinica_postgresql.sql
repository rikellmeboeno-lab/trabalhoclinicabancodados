CREATE TABLE status (
    id_status INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(30) NOT NULL UNIQUE,
    CONSTRAINT chk_status_descricao CHECK (descricao IN ('Agendado', 'Realizado', 'Cancelado', 'Pendente'))
);

CREATE TABLE paciente (
    id_paciente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_paciente VARCHAR(120) NOT NULL,
    data_nascimento DATE NOT NULL,
    cpf VARCHAR(14) NOT NULL UNIQUE,
    email VARCHAR(120) UNIQUE,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_paciente_cpf CHECK (cpf ~ '^[0-9]{3}\.[0-9]{3}\.[0-9]{3}-[0-9]{2}$'),
    CONSTRAINT chk_paciente_nascimento CHECK (data_nascimento <= CURRENT_DATE),
    CONSTRAINT chk_paciente_email CHECK (email IS NULL OR email ~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$')
);

CREATE TABLE endereco (
    id_endereco INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente INTEGER NOT NULL,
    logradouro VARCHAR(150) NOT NULL,
    numero VARCHAR(20) NOT NULL,
    bairro VARCHAR(80) NOT NULL,
    cidade VARCHAR(80) NOT NULL,
    uf CHAR(2) NOT NULL,
    cep VARCHAR(9) NOT NULL,
    tipo_endereco VARCHAR(30) NOT NULL DEFAULT 'Residencial',
    CONSTRAINT fk_endereco_paciente FOREIGN KEY (id_paciente)
        REFERENCES paciente (id_paciente)
        ON UPDATE CASCADE
        ON DELETE CASCADE,
    CONSTRAINT chk_endereco_uf CHECK (uf ~ '^[A-Z]{2}$'),
    CONSTRAINT chk_endereco_cep CHECK (cep ~ '^[0-9]{5}-[0-9]{3}$'),
    CONSTRAINT chk_endereco_tipo CHECK (tipo_endereco IN ('Residencial', 'Comercial', 'Outro')),
    CONSTRAINT uq_endereco_paciente_tipo UNIQUE (id_paciente, tipo_endereco, cep, numero)
);

CREATE TABLE funcionario (
    id_funcionario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_funcionario VARCHAR(120) NOT NULL,
    cpf VARCHAR(14) NOT NULL UNIQUE,
    ctps VARCHAR(20) NOT NULL UNIQUE,
    cargo VARCHAR(40) NOT NULL,
    especialidade VARCHAR(80),
    crm VARCHAR(20) UNIQUE,
    salario NUMERIC(10,2) NOT NULL DEFAULT 0,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_funcionario_cpf CHECK (cpf ~ '^[0-9]{3}\.[0-9]{3}\.[0-9]{3}-[0-9]{2}$'),
    CONSTRAINT chk_funcionario_cargo CHECK (cargo IN ('Médico', 'Recepcionista', 'Técnico', 'Enfermeiro', 'Administrador')),
    CONSTRAINT chk_funcionario_salario CHECK (salario >= 0),
    CONSTRAINT chk_funcionario_medico_crm CHECK (
        (cargo = 'Médico' AND crm IS NOT NULL)
        OR
        (cargo <> 'Médico')
    )
);

CREATE TABLE telefone (
    id_telefone INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente INTEGER,
    id_funcionario INTEGER,
    numero VARCHAR(16) NOT NULL UNIQUE,
    tipo_telefone VARCHAR(20) NOT NULL,
    CONSTRAINT fk_telefone_paciente FOREIGN KEY (id_paciente)
        REFERENCES paciente (id_paciente)
        ON UPDATE CASCADE
        ON DELETE CASCADE,
    CONSTRAINT fk_telefone_funcionario FOREIGN KEY (id_funcionario)
        REFERENCES funcionario (id_funcionario)
        ON UPDATE CASCADE
        ON DELETE CASCADE,
    CONSTRAINT chk_telefone_tipo CHECK (tipo_telefone IN ('Celular', 'Residencial', 'Comercial', 'Emergência')),
    CONSTRAINT chk_telefone_numero CHECK (numero ~ '^\([0-9]{2}\) [0-9]{4,5}-[0-9]{4}$'),
    CONSTRAINT chk_telefone_dono CHECK (
        (id_paciente IS NOT NULL AND id_funcionario IS NULL)
        OR
        (id_paciente IS NULL AND id_funcionario IS NOT NULL)
    )
);

CREATE TABLE agendamento (
    id_agendamento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente INTEGER NOT NULL,
    id_funcionario INTEGER NOT NULL,
    id_status INTEGER NOT NULL,
    data_agendamento DATE NOT NULL,
    hora_agendamento TIME NOT NULL,
