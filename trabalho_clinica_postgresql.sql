CREATE OR REPLACE FUNCTION fn_atualizar_timestamp()
RETURNS TRIGGER AS $$
BEGIN
    NEW.atualizado_em := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_paciente_timestamp
BEFORE UPDATE ON paciente
FOR EACH ROW
EXECUTE FUNCTION fn_atualizar_timestamp();

CREATE TRIGGER trg_funcionario_timestamp
BEFORE UPDATE ON funcionario
FOR EACH ROW
EXECUTE FUNCTION fn_atualizar_timestamp();

CREATE TRIGGER trg_agendamento_timestamp
BEFORE UPDATE ON agendamento
FOR EACH ROW
EXECUTE FUNCTION fn_atualizar_timestamp();

CREATE TRIGGER trg_exame_timestamp
BEFORE UPDATE ON exame
