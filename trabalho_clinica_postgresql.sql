CREATE OR REPLACE VIEW vw_agendamentos_detalhados AS
SELECT
    a.id_agendamento,
    p.nome_paciente,
    p.cpf AS cpf_paciente,
    f.nome_funcionario,
    f.cargo,
    f.especialidade,
    s.descricao AS status_agendamento,
    a.data_agendamento,
    a.hora_agendamento,
    a.valor_consulta,
    a.observacao
FROM agendamento a
JOIN paciente p ON p.id_paciente = a.id_paciente
JOIN funcionario f ON f.id_funcionario = a.id_funcionario
JOIN status s ON s.id_status = a.id_status;

CREATE OR REPLACE VIEW vw_exames_detalhados AS
SELECT
    e.id_exame,
    e.tipo_exame,
    e.data_exame,
    e.hora_exame,
    e.valor_exame,
    se.descricao AS status_exame,
    p.nome_paciente,
    f.nome_funcionario AS profissional_agendamento,
    sa.descricao AS status_agendamento
FROM exame e
JOIN agendamento a ON a.id_agendamento = e.id_agendamento
JOIN paciente p ON p.id_paciente = a.id_paciente
JOIN funcionario f ON f.id_funcionario = a.id_funcionario
JOIN status se ON se.id_status = e.id_status
JOIN status sa ON sa.id_status = a.id_status;

CREATE OR REPLACE VIEW vw_relatorio_financeiro_agendamentos AS
SELECT
    p.nome_paciente,
    COUNT(a.id_agendamento) AS total_agendamentos,
    COALESCE(SUM(a.valor_consulta), 0) AS total_consultas,
    COALESCE(SUM(e.valor_exame), 0) AS total_exames,
    COALESCE(SUM(a.valor_consulta), 0) + COALESCE(SUM(e.valor_exame), 0) AS total_geral
FROM paciente p
LEFT JOIN agendamento a ON a.id_paciente = p.id_paciente
LEFT JOIN exame e ON e.id_agendamento = a.id_agendamento
GROUP BY p.id_paciente, p.nome_paciente;

CREATE OR REPLACE VIEW vw_exames_pendentes AS
SELECT
    e.id_exame,
    e.tipo_exame,
    p.nome_paciente,
    e.data_exame,
    e.hora_exame,
    s.descricao AS status_exame
FROM exame e
JOIN status s ON s.id_status = e.id_status
JOIN agendamento a ON a.id_agendamento = e.id_agendamento
JOIN paciente p ON p.id_paciente = a.id_paciente
WHERE s.descricao IN ('Agendado', 'Pendente');

