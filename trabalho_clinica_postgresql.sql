-- Consulta 1: Agendamentos detalhados com múltiplos JOINs.
SELECT
    a.id_agendamento,
    p.nome_paciente,
    f.nome_funcionario,
    f.especialidade,
    s.descricao AS status,
    a.data_agendamento,
    a.hora_agendamento
FROM agendamento a
JOIN paciente p ON p.id_paciente = a.id_paciente
JOIN funcionario f ON f.id_funcionario = a.id_funcionario
JOIN status s ON s.id_status = a.id_status
ORDER BY a.data_agendamento, a.hora_agendamento;

-- Consulta 2: Quantidade de agendamentos por funcionário.
SELECT
    f.nome_funcionario,
    f.cargo,
    COUNT(a.id_agendamento) AS total_agendamentos
FROM funcionario f
LEFT JOIN agendamento a ON a.id_funcionario = f.id_funcionario
GROUP BY f.id_funcionario, f.nome_funcionario, f.cargo
ORDER BY total_agendamentos DESC;

-- Consulta 3: Pacientes com mais de um agendamento, usando GROUP BY e HAVING.
SELECT
    p.nome_paciente,
    COUNT(a.id_agendamento) AS total_agendamentos
FROM paciente p
JOIN agendamento a ON a.id_paciente = p.id_paciente
GROUP BY p.id_paciente, p.nome_paciente
HAVING COUNT(a.id_agendamento) > 1
ORDER BY total_agendamentos DESC;

-- Consulta 4: Total arrecadado por status de agendamento.
SELECT
    s.descricao AS status_agendamento,
    COUNT(a.id_agendamento) AS quantidade,
    SUM(a.valor_consulta) AS total_consultas
FROM status s
JOIN agendamento a ON a.id_status = s.id_status
GROUP BY s.descricao
ORDER BY total_consultas DESC;

-- Consulta 5: Exames por paciente com valor total, incluindo JOINs múltiplos.
SELECT
    p.nome_paciente,
    COUNT(e.id_exame) AS quantidade_exames,
    SUM(e.valor_exame) AS valor_total_exames
FROM paciente p
JOIN agendamento a ON a.id_paciente = p.id_paciente
JOIN exame e ON e.id_agendamento = a.id_agendamento
GROUP BY p.id_paciente, p.nome_paciente
ORDER BY valor_total_exames DESC;

-- Consulta 6: Pacientes que possuem exames pendentes usando subconsulta.
SELECT
    p.nome_paciente,
    p.cpf
FROM paciente p
WHERE p.id_paciente IN (
    SELECT a.id_paciente
    FROM agendamento a
    JOIN exame e ON e.id_agendamento = a.id_agendamento
    JOIN status s ON s.id_status = e.id_status
    WHERE s.descricao = 'Pendente'
)
ORDER BY p.nome_paciente;

-- Consulta 7: Funcionários que solicitaram ou realizaram mais de um exame.
SELECT
    f.nome_funcionario,
    f.cargo,
    COUNT(ef.id_exame) AS total_exames_relacionados
FROM funcionario f
JOIN exame_funcionario ef ON ef.id_funcionario = f.id_funcionario
GROUP BY f.id_funcionario, f.nome_funcionario, f.cargo
HAVING COUNT(ef.id_exame) > 1
ORDER BY total_exames_relacionados DESC;

-- Consulta 8: Próximo agendamento de cada paciente com subconsulta correlacionada.
SELECT
    p.nome_paciente,
    (
        SELECT MIN(a2.data_agendamento)
        FROM agendamento a2
        JOIN status s2 ON s2.id_status = a2.id_status
        WHERE a2.id_paciente = p.id_paciente
          AND s2.descricao <> 'Cancelado'
    ) AS proxima_data_agendamento
FROM paciente p
ORDER BY p.nome_paciente;

-- Consulta 9: Telefones e endereços agrupados por paciente.
SELECT
    p.nome_paciente,
    STRING_AGG(DISTINCT t.numero, ', ') AS telefones,
    STRING_AGG(DISTINCT e.logradouro || ', ' || e.numero || ' - ' || e.cidade || '/' || e.uf, ' | ') AS enderecos
FROM paciente p
LEFT JOIN telefone t ON t.id_paciente = p.id_paciente
LEFT JOIN endereco e ON e.id_paciente = p.id_paciente
GROUP BY p.id_paciente, p.nome_paciente
ORDER BY p.nome_paciente;

-- Consulta 10: Média de valor de consultas por especialidade, filtrando especialidades com média acima de 180.
SELECT
    f.especialidade,
    COUNT(a.id_agendamento) AS total_consultas,
    ROUND(AVG(a.valor_consulta), 2) AS media_valor_consulta
FROM funcionario f
JOIN agendamento a ON a.id_funcionario = f.id_funcionario
WHERE f.especialidade IS NOT NULL
GROUP BY f.especialidade
HAVING AVG(a.valor_consulta) > 180
ORDER BY media_valor_consulta DESC;

