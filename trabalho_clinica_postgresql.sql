CREATE OR REPLACE FUNCTION fn_validar_agendamento()
RETURNS TRIGGER AS $$
DECLARE
    v_status_descricao VARCHAR(30);
    v_funcionario_ativo BOOLEAN;
    v_cargo VARCHAR(40);
BEGIN
    SELECT descricao
      INTO v_status_descricao
      FROM status
     WHERE id_status = NEW.id_status;

    SELECT ativo, cargo
      INTO v_funcionario_ativo, v_cargo
      FROM funcionario
     WHERE id_funcionario = NEW.id_funcionario;

    IF v_funcionario_ativo IS DISTINCT FROM TRUE THEN
        RAISE EXCEPTION 'Não é permitido agendar consulta para funcionário inativo.';
    END IF;

    IF v_cargo NOT IN ('Médico', 'Enfermeiro') THEN
        RAISE EXCEPTION 'Somente médico ou enfermeiro pode ser responsável por agendamento clínico.';
    END IF;

    IF v_status_descricao = 'Cancelado' AND COALESCE(TRIM(NEW.observacao), '') = '' THEN
        RAISE EXCEPTION 'Agendamento cancelado precisa possuir observação com motivo.';
    END IF;

    IF v_status_descricao <> 'Cancelado' THEN
        IF EXISTS (
            SELECT 1
              FROM agendamento a
              JOIN status s ON s.id_status = a.id_status
             WHERE a.id_funcionario = NEW.id_funcionario
               AND a.data_agendamento = NEW.data_agendamento
               AND a.hora_agendamento = NEW.hora_agendamento
               AND s.descricao <> 'Cancelado'
               AND a.id_agendamento <> COALESCE(NEW.id_agendamento, -1)
        ) THEN
            RAISE EXCEPTION 'Funcionário já possui agendamento neste dia e horário.';
        END IF;

        IF EXISTS (
            SELECT 1
              FROM agendamento a
              JOIN status s ON s.id_status = a.id_status
             WHERE a.id_paciente = NEW.id_paciente
               AND a.data_agendamento = NEW.data_agendamento
               AND a.hora_agendamento = NEW.hora_agendamento
               AND s.descricao <> 'Cancelado'
               AND a.id_agendamento <> COALESCE(NEW.id_agendamento, -1)
        ) THEN
            RAISE EXCEPTION 'Paciente já possui agendamento neste dia e horário.';
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_validar_agendamento
BEFORE INSERT OR UPDATE ON agendamento
FOR EACH ROW
EXECUTE FUNCTION fn_validar_agendamento();

CREATE OR REPLACE FUNCTION fn_validar_exame()
RETURNS TRIGGER AS $$
DECLARE
    v_status_agendamento VARCHAR(30);
    v_data_agendamento DATE;
BEGIN
    SELECT s.descricao, a.data_agendamento
      INTO v_status_agendamento, v_data_agendamento
      FROM agendamento a
      JOIN status s ON s.id_status = a.id_status
     WHERE a.id_agendamento = NEW.id_agendamento;

    IF v_status_agendamento = 'Cancelado' THEN
        RAISE EXCEPTION 'Não é permitido cadastrar exame para agendamento cancelado.';
    END IF;

    IF NEW.data_exame < v_data_agendamento THEN
        RAISE EXCEPTION 'Data do exame não pode ser anterior à data do agendamento.';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_validar_exame
BEFORE INSERT OR UPDATE ON exame
FOR EACH ROW
EXECUTE FUNCTION fn_validar_exame();

CREATE OR REPLACE FUNCTION fn_log_agendamento()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO log_auditoria (tabela_afetada, operacao, descricao)
    VALUES (
        'agendamento',
        TG_OP,
        'Agendamento ID ' || COALESCE(NEW.id_agendamento, OLD.id_agendamento) || ' sofreu operação ' || TG_OP
    );

    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_log_agendamento
AFTER INSERT OR UPDATE OR DELETE ON agendamento
FOR EACH ROW
EXECUTE FUNCTION fn_log_agendamento();

CREATE OR REPLACE PROCEDURE sp_criar_agendamento(
    p_id_paciente INTEGER,
    p_id_funcionario INTEGER,
    p_data_agendamento DATE,
    p_hora_agendamento TIME,
    p_observacao TEXT DEFAULT NULL,
    p_valor_consulta NUMERIC DEFAULT 0
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_status_agendado INTEGER;
BEGIN
    SELECT id_status
      INTO v_status_agendado
      FROM status
     WHERE descricao = 'Agendado';

    IF v_status_agendado IS NULL THEN
        RAISE EXCEPTION 'Status Agendado não cadastrado.';
    END IF;

    INSERT INTO agendamento (
        id_paciente,
        id_funcionario,
        id_status,
        data_agendamento,
        hora_agendamento,
        observacao,
        valor_consulta
    ) VALUES (
        p_id_paciente,
        p_id_funcionario,
        v_status_agendado,
        p_data_agendamento,
        p_hora_agendamento,
        p_observacao,
        p_valor_consulta
    );
END;
$$;

CREATE OR REPLACE PROCEDURE sp_cancelar_agendamento(
    p_id_agendamento INTEGER,
    p_motivo TEXT
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_status_cancelado INTEGER;
BEGIN
    IF COALESCE(TRIM(p_motivo), '') = '' THEN
        RAISE EXCEPTION 'É obrigatório informar o motivo do cancelamento.';
    END IF;

    SELECT id_status
      INTO v_status_cancelado
      FROM status
     WHERE descricao = 'Cancelado';

    IF v_status_cancelado IS NULL THEN
        RAISE EXCEPTION 'Status Cancelado não cadastrado.';
    END IF;

    UPDATE agendamento
       SET id_status = v_status_cancelado,
           observacao = COALESCE(observacao || ' | ', '') || 'Cancelado: ' || p_motivo
     WHERE id_agendamento = p_id_agendamento;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Agendamento % não encontrado.', p_id_agendamento;
    END IF;

    UPDATE exame
       SET id_status = v_status_cancelado
     WHERE id_agendamento = p_id_agendamento;
END;
$$;

CREATE OR REPLACE PROCEDURE sp_transferir_valor(
    p_id_conta_origem INTEGER,
    p_id_conta_destino INTEGER,
    p_valor NUMERIC
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_saldo_origem NUMERIC(12,2);
BEGIN
    IF p_valor <= 0 THEN
        RAISE EXCEPTION 'Valor de transferência deve ser maior que zero.';
    END IF;

    IF p_id_conta_origem = p_id_conta_destino THEN
        RAISE EXCEPTION 'Conta de origem e destino não podem ser iguais.';
    END IF;

    SELECT saldo
      INTO v_saldo_origem
      FROM conta_financeira
     WHERE id_conta = p_id_conta_origem
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Conta de origem não encontrada.';
    END IF;

    PERFORM 1
      FROM conta_financeira
     WHERE id_conta = p_id_conta_destino
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Conta de destino não encontrada.';
    END IF;

    IF v_saldo_origem < p_valor THEN
        RAISE EXCEPTION 'Saldo insuficiente para transferência. Saldo atual: %', v_saldo_origem;
    END IF;

    UPDATE conta_financeira
       SET saldo = saldo - p_valor
     WHERE id_conta = p_id_conta_origem;

    UPDATE conta_financeira
       SET saldo = saldo + p_valor
     WHERE id_conta = p_id_conta_destino;
END;
$$;

